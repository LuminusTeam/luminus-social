/* Nyhetsbrev: tar emot formuläret på /nyhetsbrev och lägger adressen i MailerLite (SM-12, LUM-16, k-045).
   AI-skapat (B-051). Generated by AI, Directed by MS.
   Dubbel opt-in: vi skickar ingen status. Då styr MailerLite-kontots inställning för dubbel opt-in,
   och ny prenumerant blir "unconfirmed" och får ett bekräftelsemejl. Inställningen måste vara på i kontot.
   Nyckeln läses ur miljövariabeln MAILERLITE_API_KEY och gruppen ur MAILERLITE_GROUP_ID. Saknas någon är formuläret avstängt.
   Vi skickar bara e-postadressen. Ingen IP-adress och inget namn skickas vidare, och adressen loggas inte. */
const traffar = new Map();
const TACK = '/nyhetsbrev-tack', FEL = '/nyhetsbrev-fel';
const EPOST = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/;
export default async function handler(req, res) {
  const till = (vag) => { res.statusCode = 303; res.setHeader('Location', vag); res.setHeader('Cache-Control', 'no-store'); return res.end(); };
  if (req.method !== 'POST') { res.statusCode = 405; res.setHeader('Allow', 'POST'); return res.end(); }
  const nyckel = (process.env.MAILERLITE_API_KEY || '').trim();
  const grupp = (process.env.MAILERLITE_GROUP_ID || '').trim();
  if (!nyckel || !grupp) return till(FEL);
  const b = req.body && typeof req.body === 'object' ? req.body : {};
  if (String(b.webbplats || '') !== '') return till(TACK); /* fälla för robotar: låtsas att det gick */
  const epost = String(b.epost || '').trim().toLowerCase();
  if (b.samtycke !== 'ja' || epost.length > 254 || !EPOST.test(epost)) return till(FEL);
  const vem = String(req.headers['x-forwarded-for'] || '').split(',')[0].trim() || 'okand';
  const nu = Date.now();
  const lista = (traffar.get(vem) || []).filter((t) => nu - t < 36e5);
  if (lista.length >= 5) return till(FEL);
  lista.push(nu); traffar.set(vem, lista);
  try {
    const r = await fetch('https://connect.mailerlite.com/api/subscribers', {
      method: 'POST',
      headers: { authorization: 'Bearer ' + nyckel, 'content-type': 'application/json', accept: 'application/json' },
      body: JSON.stringify({ email: epost, groups: [grupp] }),
    });
    if (!r.ok) { console.error('mailerlite', r.status); return till(FEL); }
    return till(TACK);
  } catch { console.error('mailerlite', 'natfel'); return till(FEL); }
}
