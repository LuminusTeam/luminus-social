#!/usr/bin/env node
// F76 Nyhetskoll.
// Användning: node scripts/nyhetskoll.cjs [--rot <katalog>]
// Läser <rot>/public/data/nytt.json mot sidorna i <rot>/public/ och listar
//   - poster med status forhandsgranskning vars interna länk leder till en sida som finns (kan bli live),
//   - poster med status forhandsgranskning utan länk (kontrolleras för hand),
//   - poster (alla statusar) vars interna länk leder till en sida som saknas (brutna),
//   - fristående sidor som ingen post länkar till (utom index, 404 och nyhetsbrev).
// Länkar tolkas som Vercel med cleanUrls: /x → x.html eller x/index.html, / och /#vy → index.html.
// Skriptet läser bara: det skriver ingen fil, kör inget git och hämtar inget från nätet.
// Utgångskod: 0 inga brutna länkar, 1 minst en bruten länk, 2 fel i anropet eller oläsbar nytt.json.
// AI-skapat (B-051). Generated by AI, Directed by MS.
const fs = require('fs');
const path = require('path');

function sidaFor(publicDir, lank) {
  if (!lank) return { typ: 'ingen' };
  if (/^(https?:)?\/\//i.test(lank)) return { typ: 'extern' };
  if (!lank.startsWith('/')) return { typ: 'okand' };
  let v = lank.replace(/[#?].*$/, '');
  if (v === '' || v === '/') return { typ: 'intern', fil: 'index.html', finns: fs.existsSync(path.join(publicDir, 'index.html')) };
  v = v.replace(/^\//, '').replace(/\/$/, '');
  const kandidater = v.endsWith('.html') ? [v] : [v + '.html', path.join(v, 'index.html')];
  const hittad = kandidater.find((k) => fs.existsSync(path.join(publicDir, k)));
  return { typ: 'intern', fil: hittad || kandidater[0], finns: !!hittad };
}

function granska(rot) {
  const publicDir = path.join(rot, 'public');
  const data = JSON.parse(fs.readFileSync(path.join(publicDir, 'data', 'nytt.json'), 'utf8'));
  const poster = Array.isArray(data.poster) ? data.poster : [];
  const kort = (p) => ({ datum: p.datum, titel: p.titel, status: p.status, lank: p.lank || null });
  const kandidaterLive = [];
  const utanLank = [];
  const brutna = [];
  const traffade = new Set();
  for (const p of poster) {
    const s = sidaFor(publicDir, p.lank);
    if (s.typ === 'intern' && s.finns) traffade.add(s.fil.split(path.sep).join('/'));
    if (s.typ === 'intern' && !s.finns) brutna.push(kort(p));
    if (p.status !== 'forhandsgranskning') continue;
    if (s.typ === 'intern' && s.finns) kandidaterLive.push(kort(p));
    else if (s.typ === 'ingen') utanLank.push(kort(p));
  }
  const sidorUtanPost = fs.readdirSync(publicDir)
    .filter((f) => f.endsWith('.html') && f !== 'index.html' && f !== '404.html' && !/^nyhetsbrev/.test(f))
    .filter((f) => !traffade.has(f))
    .sort();
  return { poster: poster.length, kandidaterLive, utanLank, brutna, sidorUtanPost, ok: brutna.length === 0 };
}

function main(argv) {
  let rot = process.cwd();
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--rot') {
      if (!argv[i + 1] || argv[i + 1].startsWith('-')) return { kod: 2, fel: '--rot saknar värde' };
      rot = path.resolve(argv[++i]);
    } else return { kod: 2, fel: 'okänt argument: ' + argv[i] };
  }
  let r;
  try { r = granska(rot); } catch (e) { return { kod: 2, fel: 'kan inte läsa public/data/nytt.json: ' + e.message }; }
  const rad = (p) => `  ${p.datum} ${p.titel}${p.lank ? ` (${p.lank})` : ''}`;
  console.log(`Poster: ${r.poster}`);
  console.log(`Kan bli live: ${r.kandidaterLive.length}`); r.kandidaterLive.forEach((p) => console.log(rad(p)));
  console.log(`Förhandsgranskning utan länk, kontrollera för hand: ${r.utanLank.length}`); r.utanLank.forEach((p) => console.log(rad(p)));
  console.log(`Brutna länkar: ${r.brutna.length}`); r.brutna.forEach((p) => console.log(rad(p)));
  console.log(`Sidor utan post: ${r.sidorUtanPost.join(', ') || 'inga'}`);
  console.log(JSON.stringify(r));
  return { kod: r.ok ? 0 : 1 };
}

module.exports = { granska, sidaFor };

if (require.main === module) {
  const r = main(process.argv.slice(2));
  if (r.fel) console.error('nyhetskoll: ' + r.fel);
  process.exit(r.kod);
}
