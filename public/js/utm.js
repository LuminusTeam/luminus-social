/* UTM-standard för luminusloom.net (SM-19, LUM-23, k-052).
   AI-skapat (B-051). Generated by AI, Directed by MS.
   Källa: "Fristerna 12 nov – jourlista, social_posts och UTM (2026-11-12)" avsnitt 3.
   Fyra parametrar, gemener, bindestreck, inga å, ä, ö. Biografilänkar: utm_medium=profil och ingen utm_content. */
(function (rot) {
  var KANALER = ['instagram', 'facebook', 'youtube', 'threads', 'bluesky', 'linkedin', 'nyhetsbrev', 'spotify'];
  var MEDIER = ['social', 'email', 'profil'];
  var GILTIGT = /^[a-z0-9]+(-[a-z0-9]+)*$/;

  /* Gör om fri text till ett giltigt värde: "Vreta kök v47" blir "vreta-kok-v47". */
  function rensa(text) {
    return String(text == null ? '' : text).toLowerCase()
      .replace(/[åä]/g, 'a').replace(/ö/g, 'o')
      .normalize('NFD').replace(/[̀-ͯ]/g, '')
      .replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
  }

  /* Returnerar en lista med fel; tom lista betyder att värdena följer standarden. */
  function kontrollera(v) {
    var fel = [];
    v = v || {};
    if (KANALER.indexOf(v.source) < 0) fel.push('utm_source ska vara en av: ' + KANALER.join(', '));
    if (MEDIER.indexOf(v.medium) < 0) fel.push('utm_medium ska vara social, email eller profil');
    if (!GILTIGT.test(v.campaign || '')) fel.push('utm_campaign ska vara gemener, siffror och bindestreck');
    if (v.medium === 'profil' && v.content) fel.push('biografilänkar har ingen utm_content');
    if (v.medium !== 'profil' && !GILTIGT.test(v.content || '')) fel.push('utm_content ska vara id i social_posts');
    return fel;
  }

  /* Bygger länken. Kastar fel om värdena bryter mot standarden, så att ingen felmärkt länk går ut. */
  function lank(adress, v) {
    var fel = kontrollera(v);
    if (fel.length) throw new Error('UTM: ' + fel.join('; '));
    var u = new URL(adress);
    ['utm_source', 'utm_medium', 'utm_campaign', 'utm_content'].forEach(function (p) { u.searchParams.delete(p); });
    u.searchParams.set('utm_source', v.source);
    u.searchParams.set('utm_medium', v.medium);
    u.searchParams.set('utm_campaign', v.campaign);
    if (v.medium !== 'profil') u.searchParams.set('utm_content', v.content);
    return u.toString();
  }

  rot.LuminusUtm = { KANALER: KANALER, MEDIER: MEDIER, rensa: rensa, kontrollera: kontrollera, lank: lank };
})(typeof window !== 'undefined' ? window : globalThis);
